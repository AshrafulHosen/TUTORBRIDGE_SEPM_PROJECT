-- TutorBridge initial schema.
-- Relationship kinds: 1:1 (users-profiles, applications-demo_sessions, tuition_posts-reviews),
-- 1:M / M:1 (users-tuition_posts, tuition_posts-applications, users-notifications, ...),
-- M:M (tutor_profiles-subjects, tutor_profiles-areas, tuition_posts-subjects).

-- ---------------------------------------------------------------------------
-- Users and profiles
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_users_role   CHECK (role IN ('ADMIN', 'TUTOR', 'GUARDIAN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);
CREATE UNIQUE INDEX uq_users_email ON users (LOWER(email));
CREATE INDEX ix_users_role ON users (role);

CREATE TABLE subjects (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT uq_subjects_name UNIQUE (name)
);

CREATE TABLE areas (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT uq_areas_name UNIQUE (name)
);

CREATE TABLE tutor_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT           NOT NULL,
    institution  VARCHAR(150),
    bio          VARCHAR(1000),
    salary_min   INTEGER,
    salary_max   INTEGER,
    verified     BOOLEAN          NOT NULL DEFAULT FALSE,
    rating_avg   DOUBLE PRECISION NOT NULL DEFAULT 0,
    rating_count INTEGER          NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ      NOT NULL,
    updated_at   TIMESTAMPTZ      NOT NULL,
    CONSTRAINT uq_tutor_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_tutor_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_tutor_profiles_salary_min CHECK (salary_min IS NULL OR salary_min > 0),
    CONSTRAINT ck_tutor_profiles_salary_range
        CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min),
    CONSTRAINT ck_tutor_profiles_rating CHECK (rating_avg >= 0 AND rating_avg <= 5 AND rating_count >= 0)
);

CREATE TABLE guardian_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL,
    home_area_id BIGINT,
    address      VARCHAR(200),
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_guardian_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_guardian_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_guardian_profiles_area FOREIGN KEY (home_area_id) REFERENCES areas (id)
);

-- M:M join tables for tutors
CREATE TABLE tutor_subjects (
    tutor_profile_id BIGINT NOT NULL,
    subject_id       BIGINT NOT NULL,
    PRIMARY KEY (tutor_profile_id, subject_id),
    CONSTRAINT fk_tutor_subjects_tutor   FOREIGN KEY (tutor_profile_id) REFERENCES tutor_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_tutor_subjects_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
);
CREATE INDEX ix_tutor_subjects_subject ON tutor_subjects (subject_id);

CREATE TABLE tutor_areas (
    tutor_profile_id BIGINT NOT NULL,
    area_id          BIGINT NOT NULL,
    PRIMARY KEY (tutor_profile_id, area_id),
    CONSTRAINT fk_tutor_areas_tutor FOREIGN KEY (tutor_profile_id) REFERENCES tutor_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_tutor_areas_area  FOREIGN KEY (area_id) REFERENCES areas (id)
);
CREATE INDEX ix_tutor_areas_area ON tutor_areas (area_id);

-- String collections (kept as simple join tables of values)
CREATE TABLE tutor_class_levels (
    tutor_profile_id BIGINT      NOT NULL,
    class_level      VARCHAR(30) NOT NULL,
    PRIMARY KEY (tutor_profile_id, class_level),
    CONSTRAINT fk_tutor_class_levels_tutor FOREIGN KEY (tutor_profile_id) REFERENCES tutor_profiles (id) ON DELETE CASCADE
);

CREATE TABLE tutor_mediums (
    tutor_profile_id BIGINT      NOT NULL,
    medium           VARCHAR(30) NOT NULL,
    PRIMARY KEY (tutor_profile_id, medium),
    CONSTRAINT fk_tutor_mediums_tutor FOREIGN KEY (tutor_profile_id) REFERENCES tutor_profiles (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Tuition posts and applications
-- ---------------------------------------------------------------------------
CREATE TABLE tuition_posts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guardian_id   BIGINT       NOT NULL,
    area_id       BIGINT       NOT NULL,
    title         VARCHAR(120) NOT NULL,
    class_level   VARCHAR(30)  NOT NULL,
    medium        VARCHAR(30)  NOT NULL,
    salary        INTEGER      NOT NULL,
    days_per_week INTEGER      NOT NULL,
    details       VARCHAR(1000),
    status        VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_tuition_posts_guardian FOREIGN KEY (guardian_id) REFERENCES users (id),
    CONSTRAINT fk_tuition_posts_area     FOREIGN KEY (area_id) REFERENCES areas (id),
    CONSTRAINT ck_tuition_posts_status   CHECK (status IN ('OPEN', 'IN_REVIEW', 'FILLED', 'CLOSED')),
    CONSTRAINT ck_tuition_posts_salary   CHECK (salary > 0),
    CONSTRAINT ck_tuition_posts_days     CHECK (days_per_week BETWEEN 1 AND 7)
);
CREATE INDEX ix_tuition_posts_status_area ON tuition_posts (status, area_id);
CREATE INDEX ix_tuition_posts_guardian ON tuition_posts (guardian_id, created_at DESC);

CREATE TABLE post_subjects (
    post_id    BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    PRIMARY KEY (post_id, subject_id),
    CONSTRAINT fk_post_subjects_post    FOREIGN KEY (post_id) REFERENCES tuition_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_subjects_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
);
CREATE INDEX ix_post_subjects_subject ON post_subjects (subject_id);

CREATE TABLE applications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT      NOT NULL,
    tutor_id    BIGINT      NOT NULL,
    cover_note  VARCHAR(500),
    match_score INTEGER     NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'APPLIED',
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_applications_post  FOREIGN KEY (post_id) REFERENCES tuition_posts (id),
    CONSTRAINT fk_applications_tutor FOREIGN KEY (tutor_id) REFERENCES users (id),
    CONSTRAINT uq_applications_post_tutor UNIQUE (post_id, tutor_id),
    CONSTRAINT ck_applications_score  CHECK (match_score BETWEEN 0 AND 100),
    CONSTRAINT ck_applications_status CHECK (status IN
        ('APPLIED', 'SHORTLISTED', 'DEMO_SCHEDULED', 'ACCEPTED', 'REJECTED', 'WITHDRAWN'))
);
CREATE INDEX ix_applications_post_status ON applications (post_id, status);
CREATE INDEX ix_applications_tutor ON applications (tutor_id);

CREATE TABLE demo_sessions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL,
    scheduled_at   TIMESTAMPTZ  NOT NULL,
    mode           VARCHAR(20)  NOT NULL,
    location       VARCHAR(200),
    notes          VARCHAR(500),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_demo_sessions_application UNIQUE (application_id),
    CONSTRAINT fk_demo_sessions_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
    CONSTRAINT ck_demo_sessions_mode CHECK (mode IN ('ONLINE', 'IN_PERSON'))
);

CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT      NOT NULL,
    guardian_id BIGINT      NOT NULL,
    tutor_id    BIGINT      NOT NULL,
    rating      INTEGER     NOT NULL,
    comment     VARCHAR(500),
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_reviews_post UNIQUE (post_id),
    CONSTRAINT fk_reviews_post     FOREIGN KEY (post_id) REFERENCES tuition_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_guardian FOREIGN KEY (guardian_id) REFERENCES users (id),
    CONSTRAINT fk_reviews_tutor    FOREIGN KEY (tutor_id) REFERENCES users (id),
    CONSTRAINT ck_reviews_rating   CHECK (rating BETWEEN 1 AND 5)
);
CREATE INDEX ix_reviews_tutor ON reviews (tutor_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Notifications, audit log and revoked tokens
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT       NOT NULL,
    type         VARCHAR(40)  NOT NULL,
    message      VARCHAR(300) NOT NULL,
    link         VARCHAR(200),
    is_read      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_notifications_recipient_created ON notifications (recipient_id, created_at DESC);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT      NOT NULL,
    action      VARCHAR(50) NOT NULL,
    target_type VARCHAR(30) NOT NULL,
    target_id   BIGINT,
    details     VARCHAR(500),
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_audit_logs_admin FOREIGN KEY (admin_id) REFERENCES users (id)
);
CREATE INDEX ix_audit_logs_created ON audit_logs (created_at DESC);

CREATE TABLE revoked_tokens (
    jti        VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_revoked_tokens_expires ON revoked_tokens (expires_at);

